const { test } = require("node:test");
const assert = require("node:assert/strict");
const express = require("express");
const jwt = require("jsonwebtoken");
const { spawnSync } = require("node:child_process");
const User = require("../models/User");
const Appointment = require("../models/Appointment");
const Consultation = require("../models/Consultation");
const Prescription = require("../models/Prescription");
const patientRouter = require("../routes/patientClinical");
const doctorRouter = require("../routes/doctorClinical");
const { errorHandler } = require("../middleware/errorHandler");
const patient = "507f1f77bcf86cd799439011", doctor = "507f1f77bcf86cd799439012", other = "507f1f77bcf86cd799439013";
const query = value => ({ select() { return this; }, populate() { return this; }, sort() { return this; }, lean: async () => value });
test("HTTP history is patient scoped, private-note free and approval/relationship protected", async t => {
  const original = process.env.JWT_SECRET; process.env.JWT_SECRET = "synthetic-history-http-secret";
  let account = { _id: patient, role: "patient", accountStatus: "active" }, relationship = false, reads = 0;
  t.mock.method(User, "findById", () => ({ select: async () => account }));
  t.mock.method(User, "findOne", async () => account.doctorVerificationStatus === "verified" ? account : null);
  t.mock.method(Appointment, "exists", async filter => { assert.equal(String(filter.patient), patient); assert.deepEqual(filter.status, { $in: ["scheduled", "completed"] }); return relationship ? {} : null; });
  const rows = [doctor, other].map((owner, i) => ({ _id: `synthetic-${i}`, patient, doctor: { _id: owner }, status: "completed", clinicalNotes: "Private synthetic note", appointment: { _id: `appointment-${i}`, doctor: owner, patient, status: "completed" } }));
  t.mock.method(Consultation, "find", filter => { reads++; assert.equal(filter.patient, patient); return query(rows); });
  t.mock.method(Prescription, "find", filter => { assert.equal(filter.patient, patient); return query([]); });
  const app = express(); app.use("/patient", patientRouter); app.use("/doctor", doctorRouter); app.use(errorHandler);
  const server = await new Promise(resolve => { const instance = app.listen(0, "127.0.0.1", () => resolve(instance)); });
  t.after(async () => { await new Promise(resolve => server.close(resolve)); if (original === undefined) delete process.env.JWT_SECRET; else process.env.JWT_SECRET = original; });
  const get = (path, authenticated = true) => fetch(`http://127.0.0.1:${server.address().port}${path}`, { headers: authenticated ? { authorization: `Bearer ${jwt.sign({ userId: account._id }, process.env.JWT_SECRET)}` } : {} });
  assert.equal((await get("/patient/consultations", false)).status, 401);
  const response = await get("/patient/consultations"); assert.equal(response.status, 200);
  const history = await response.json(); assert.equal(history.length, 2); assert.equal(history[0].clinicalNotes, undefined);
  assert.equal((await get("/doctor/patients/" + patient + "/history")).status, 403);
  const before = reads;
  account = { ...account, _id: doctor, role: "doctor", doctorVerificationStatus: "pending" };
  assert.equal((await get("/patient/consultations")).status, 403);
  assert.equal((await get("/doctor/patients/" + patient + "/history")).status, 403);
  account.doctorVerificationStatus = "verified";
  assert.equal((await get("/doctor/patients/" + patient + "/history")).status, 403); assert.equal(reads, before);
  relationship = true;
  const approved = await get("/doctor/patients/" + patient + "/history"); assert.equal(approved.status, 200);
  const authorized = await approved.json(); assert.equal(authorized.consultations.length, 1); assert.equal(authorized.consultations[0].doctor._id, doctor);
  account.accountStatus = "disabled";
  assert.equal((await get("/doctor/patients/" + patient + "/history")).status, 403);
});
test("maintenance CLI refuses before loading dotenv or connecting without explicit confirmation", () => {
  const result = spawnSync(process.execPath, [require.resolve("../reconcileMedicalRecords")], { encoding: "utf8", env: { ...process.env, MONGO_URI: "invalid-synthetic-do-not-connect" } });
  assert.equal(result.status, 1); assert.equal(result.stdout, "");
  assert.match(result.stderr, /Medical record maintenance failed/); assert.doesNotMatch(result.stderr, /invalid-synthetic/);
});
